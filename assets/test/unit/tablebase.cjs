const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ChessModule = require('chess.js');
const Chess = ChessModule.Chess || ChessModule;
const context = vm.createContext({require, setTimeout, clearTimeout, AbortController});
require('./chess_moves_helper.cjs')(context);
for (const name of ['tablebase', 'endgame_engine', 'engine_position']) {
    const source = fs.readFileSync(path.join(__dirname, '../../js/modules', name + '.js'), 'utf8');
    vm.runInContext(source.replace(/^import .*\n/gm, '').replace(/^export /gm, ''), context);
}
const {createTablebaseClient, tablebaseMove, tablebaseAssessment, createEndgameEngine, enginePosition} = context;
const fen = '7k/8/8/8/8/5Q2/5K2/8 b - - 0 1';
const board = new Chess(fen);
const state = {initialFen: fen, fen, moves: []};
const response = (category = 'loss') => ({category, moves: board.moves({verbose: true}).map((move, i) => ({
    uci: move.from + move.to + (move.promotion || ''), category: category === 'loss' ? 'win' : 'draw', dtm: i + 2
}))});
const ok = data => ({ok: true, status: 200, json: async () => data});
(async () => {
    const data = response();
    assert(data.moves.length > 1);
    assert.equal(tablebaseMove(state, data), data.moves.at(-1).uci, 'A losing defence maximizes known DTM, not DTZ');
    assert.equal(tablebaseMove(state, {...data, category: 'unknown'}), null);
    assert.equal(tablebaseMove(state, {...data, moves: data.moves.slice(1)}), null, 'Do not trust incomplete legal move sets');
    assert.equal(tablebaseMove(state, {...data, category: 'win'}), null, 'Reject reversed or inconsistent outcome perspectives');
    const invalid = response(); invalid.moves[0].uci = 'a1a2';
    assert.equal(tablebaseMove(state, invalid), null);
    const rounded = response(); rounded.moves[0].dtm = null;
    assert.equal(tablebaseMove(state, rounded), rounded.moves[0].uci, 'Missing DTM retains the service ordering');
    const promotion = new Chess('7k/P7/6K1/8/8/8/8/8 w - - 0 1');
    const promotionState = enginePosition(promotion.fen(), promotion);
    const promotionData = {category: 'win', moves: promotion.moves({verbose: true}).map(move => ({uci: move.from + move.to + (move.promotion || ''), category: move.promotion === 'q' || move.promotion === 'r' ? 'loss' : 'draw'}))};
    assert.equal(tablebaseAssessment(promotionState, promotionData, 'a7a8q').grade, 'acceptable', 'A winning promotion cannot be penalised by a transient engine score');
    assert.equal(tablebaseAssessment(promotionState, promotionData, 'a7a8r').grade, 'acceptable', 'Equivalent winning underpromotion is valid');
    assert.equal(tablebaseAssessment(promotionState, promotionData, 'a7a8n').moment, 'winToDraw');
    assert.equal(tablebaseAssessment(promotionState, promotionData, 'a7a8n').grade, 'mistake');
    const losingPromotion = {...promotionData, moves: promotionData.moves.map(move => ({...move, category: move.uci === 'a7a8r' ? 'win' : move.category}))};
    assert.equal(tablebaseAssessment(promotionState, losingPromotion, 'a7a8r').moment, 'winToLoss');
    assert.equal(tablebaseAssessment(promotionState, losingPromotion, 'a7a8r').grade, 'blunder');
    assert.equal(tablebaseAssessment(promotionState, {...promotionData, moves: []}, 'a7a8q'), null);
    let count = 0, clock = 1000;
    const client = createTablebaseClient({now: () => clock, fetcher: async () => {count++; return ok(data);}});
    const [first, second] = await Promise.all([client.lookup(fen), client.lookup(fen)]);
    assert.equal(count, 1); assert.deepEqual(first, second);
    await client.lookup(fen.replace('0 1', '0 99')); assert.equal(count, 1, 'Fullmove number does not invalidate a tablebase lookup');
    await client.lookup(fen.replace('0 1', '99 1')); assert.equal(count, 2, 'The fifty-move counter is part of the cache key');
    await client.lookup(new Chess().fen()); assert.equal(count, 2, 'Do not request unsupported material or castling rights');
    let unavailableCalls = 0;
    const unavailable = createTablebaseClient({now: () => clock, fetcher: async () => {
        unavailableCalls++; return {ok: false, status: 429, headers: {get: () => '60'}};
    }});
    assert.equal(await unavailable.lookup(fen), null);
    assert.equal(await unavailable.lookup(fen.replace('0 1', '1 1')), null);
    assert.equal(unavailableCalls, 1);
    clock += 61000; await unavailable.lookup(fen); assert.equal(unavailableCalls, 2);
    let missingCalls = 0;
    const missing = createTablebaseClient({fetcher: async () => {missingCalls++; return {ok: false, status: 404};}});
    await missing.lookup(fen); await missing.lookup(fen); assert.equal(missingCalls, 1);
    const timeout = createTablebaseClient({timeoutMs: 5, fetcher: () => new Promise(() => {})});
    assert.equal(await timeout.lookup(fen), null, 'A request that ignores abort still cannot stall the game');
    let localCalls = 0;
    const local = {bestMove: async () => {localCalls++; return 'h8g8';}, analyze: async () => ({}), cancel() {}, dispose() {}};
    const preferred = createEndgameEngine({local, tables: {lookup: async () => data}});
    assert.equal(await preferred.bestMove(state), data.moves.at(-1).uci); assert.equal(localCalls, 0);
    const fallback = createEndgameEngine({local, tables: {lookup: async () => {throw Error('Offline');}}});
    assert.equal(await fallback.bestMove(state), 'h8g8'); assert.equal(localCalls, 1);
    let complete;
    const cancelled = createEndgameEngine({local, tables: {lookup: () => new Promise(resolve => complete = resolve)}});
    const pending = cancelled.bestMove(state); cancelled.dispose(); complete(data);
    await assert.rejects(pending, /cancelled/); assert.equal(localCalls, 1, 'A late API result cannot restart a disposed game');
    const repetition = new Chess();
    for (const move of ['Nf3', 'Nf6', 'Ng1', 'Ng8']) repetition.move(move);
    const replay = enginePosition(new Chess().fen(), repetition);
    assert.equal(replay.moves.join(' '), 'g1f3 g8f6 f3g1 f6g8');
    assert.equal(replay.initialFen, new Chess().fen());
    const repeated = new Chess('6k1/8/8/8/8/8/8/KQ6 w - - 0 1');
    const root = repeated.fen();
    for (const san of ['Qb4', 'Kh8', 'Qb1', 'Kg8', 'Qb4', 'Kh8', 'Qb1']) assert(repeated.move(san));
    const repeatedState = enginePosition(root, repeated);
    const repeatedData = {category: 'loss', moves: repeated.moves({verbose: true}).map(move => ({uci: move.from + move.to, category: 'win', dtm: move.to === 'g8' ? 2 : 20}))};
    assert.equal(tablebaseMove(repeatedState, repeatedData), 'h8g8', 'Known threefold repetition takes precedence over a FEN-only theoretical loss');
    console.log('Tablebase coverage, move validation, resistance, caching, rate limits, timeout, fallback and stale-result checks passed');
})().catch(error => {console.error(error); process.exitCode = 1;});
