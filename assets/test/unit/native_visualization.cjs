const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const uri = source => 'data:text/javascript;base64,' + Buffer.from(source).toString('base64');
(async () => {
    const root = path.resolve(__dirname, '../../js/modules');
    const scope = uri(fs.readFileSync(path.join(root, 'page_scope.js'), 'utf8'));
    const progression = uri(fs.readFileSync(path.join(root, 'study/visualization.js'), 'utf8').replace("'../page_scope.js'", JSON.stringify(scope)));
    const source = fs.readFileSync(path.join(root, 'native_visualization.js'), 'utf8').replace("'./study/visualization.js'", JSON.stringify(progression))
        .replace("'./page_scope.js'", JSON.stringify(scope));
    const {createNativeVisualization, createPieceMask} = await import(uri(source));
    const saved = new Map();
    const storage = {getItem: key => saved.get(key) || null, setItem: (key, value) => saved.set(key, value)};
    let time = 1000;
    const tracker = createNativeVisualization({mode: 'blind', storage, now: () => ++time});
    for (let i = 0; i < 3; i++) {
        tracker.begin(String(i), tracker.level, 1);
        tracker.decision(true); tracker.end(true);
    }
    assert.equal(tracker.level, 2);
    tracker.begin('short', tracker.level, 1);
    tracker.decision(true); tracker.end(true);
    assert.equal(tracker.level, 2, 'A short exercise does not earn progression for unavailable hidden moves');
    tracker.begin('new', 2, 2);
    tracker.decision(false); tracker.decision(true); tracker.end(true);
    assert.equal(tracker.current.attempts, 2);
    assert.equal(tracker.current.errors, 1);
    assert.equal(tracker.level, 1);
    tracker.end(false, true);
    assert.equal(tracker.current.revealed, false, 'A completion can only be recorded once');
    tracker.begin('new', 1, 1);
    assert(tracker.current.rehearsed, 'An immediate retry cannot masquerade as independent recall');
    tracker.end(false, true);
    const reloaded = createNativeVisualization({mode: 'blind', storage, now: () => ++time});
    reloaded.begin('new', 1, 1);
    assert(reloaded.current.assisted, 'Viewing the solution is remembered through reloads');
    reloaded.abandon();
    assert(reloaded.current.abandoned);
    assert(!reloaded.current.completed);
    reloaded.begin('after-break', 1, 1);
    reloaded.help(); reloaded.decision(true); reloaded.end(true);
    assert(reloaded.current.assisted);
    assert.equal(reloaded.current.hiddenMoves, 1);
    assert.equal(reloaded.current.hiddenPieces, 0);
    const pieces = createNativeVisualization({mode: 'pieceless', storage, now: () => ++time});
    assert.equal(pieces.level, 1, 'Blind and Pieceless progress are independent');
    for (let target of [1, 2, 4, 8, 16]) for (let i = 0; i < 3; i++) {
        assert.equal(pieces.level, target);
        pieces.begin(`${target}-${i}`, target, target);
        pieces.decision(true); pieces.end(true);
    }
    assert.equal(pieces.level, 32);
    pieces.begin('classic', 32, 3); pieces.decision(true); pieces.end(true);
    assert.equal(pieces.current.hiddenPieces, 3);
    assert.equal(pieces.level, 32);
    const unavailable = createNativeVisualization({mode: 'blind', storage: {getItem() {throw Error();}, setItem() {throw Error();}}});
    unavailable.begin('offline', 1, 1); unavailable.decision(true); unavailable.end(true);
    assert(unavailable.current.completed);
    global.MutationObserver = class { observe() {} disconnect() {} };
    const node = square => ({cgKey: square, hidden: false, classList: {toggle(_name, value) {this.owner.hidden = value;}}});
    const rook = node('a1'); rook.classList.owner = rook;
    let mask = createPieceMask({querySelectorAll: () => [rook]}, ['a1']);
    assert(rook.hidden);
    rook.cgKey = 'd1';
    mask.move({from: 'e1', to: 'c1', flags: 'q'});
    assert(rook.hidden, 'A hidden rook remains hidden after castling');
    rook.cgKey = 'd8'; mask.move({from: 'd1', to: 'd8', flags: 'c'});
    assert(rook.hidden, 'The identity remains hidden through a capture');
    mask.destroy();
    const pawn = node('a7'); pawn.classList.owner = pawn;
    mask = createPieceMask({querySelectorAll: () => [pawn]}, ['a7']);
    pawn.cgKey = 'a8'; mask.move({from: 'a7', to: 'a8', flags: 'p'});
    assert(pawn.hidden, 'Promotion does not reveal a hidden piece');
    mask.destroy();
    console.log('Native visualization persistence, adaptive difficulty, assistance and retry accounting passed');
})().catch(error => {console.error(error); process.exitCode = 1;});
