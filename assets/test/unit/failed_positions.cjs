const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname, '../../js/modules/study/failed_positions.js'), 'utf8')
    .replace(/export \{[^}]+\};/, ''), context);
const { chapterFailures, recordPositionResult, pendingPositions } = context;
const stats = { chapters: {}, chapterIds: ['stable-id'] };
let positions = chapterFailures(stats, 0, 'original');
const details = { path: [0], fen: 'position', played: 'd4', expected: ['e4'] };
recordPositionResult(positions, 'e5', details, false);
recordPositionResult(positions, 'e5', { ...details, played: 'c4' }, false);
assert.equal(pendingPositions(positions).length, 1);
assert.equal(positions.e5.failures, 2);
assert.equal(positions.e5.played, 'c4');
assert.equal(stats.chapters['stable-id'].errors, 0);
recordPositionResult(positions, 'unknown', details, true);
assert.equal(Object.keys(positions).length, 1);
for (let i = 0; i < 3; i++) recordPositionResult(positions, 'e5', details, true);
assert.equal(pendingPositions(positions).length, 0);
recordPositionResult(positions, 'e5', details, false);
assert.equal(pendingPositions(positions).length, 1);
assert.equal(positions.e5.failures, 3);
const restored = JSON.parse(JSON.stringify(stats));
restored.chapterIds = ['other-id', 'stable-id'];
assert.equal(pendingPositions(chapterFailures(restored, 1, 'original')).length, 1);
assert.equal(pendingPositions(chapterFailures(restored, 1, 'edited')).length, 0);
assert.equal(pendingPositions(chapterFailures({ chapters: { 0: { attempts: 5, errors: 2 } } }, 0, 'new')).length, 0);
console.log('Failed position persistence and recovery passed');

recordPositionResult(positions, 'hint', details, true, { recovered: false });
assert.equal(positions.hint.recovered, false);
recordPositionResult(positions, 'hint', details, true);
assert.equal(positions.hint.recovered, false);
recordPositionResult(positions, 'hint', details, true, { recovered: true });
assert.equal(positions.hint.recovered, true);
recordPositionResult(positions, 'hint', details, false, { recovered: false });
assert.equal(positions.hint.recovered, false);
