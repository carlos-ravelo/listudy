const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const context = vm.createContext({ ...require('ts-fsrs'), ChessModule: require('chess.js') });
vm.runInContext(fs.readFileSync(path.join(__dirname, '../../js/modules/study/review_history.js'), 'utf8').replace(/export \{[^}]+\};/, ''), context);
vm.runInContext(fs.readFileSync(path.join(__dirname, '../../js/modules/study/position_review.js'), 'utf8')
    .replace(/^import .*\n/gm, '').replace(/export \{[^}]+\};/, ''), context);
const { positionReviews, positionCatalog, recordPositionReview, nextSmartPosition } = context;
const now = new Date('2026-10-14T10:00:00Z');
const later = seconds => new Date(now.getTime() + seconds * 1000);
const stats = { chapters: {}, chapterIds: ['stable', 'second'] };
const signatures = ['a', 'b'];
const cards = positionReviews(stats, 0, 'a');
const attempts = new Set();
const failed = recordPositionReview(cards, '', false, false, attempts, now);
assert.equal(failed.recovered, false);
const retry = recordPositionReview(cards, '', true, false, attempts, later(1));
assert.equal(retry, null);
assert.equal(cards[''].recovered, false);
assert.equal(cards[''].successes, 0);
const before = JSON.stringify(cards['']);
recordPositionReview(cards, '', true, false, new Set(), later(20));
assert.equal(JSON.stringify(cards['']), before);
recordPositionReview(cards, '', true, false, new Set(), new Date(cards[''].card.due));
assert.equal(cards[''].recovered, true);
const due = cards[''].card.due;
recordPositionReview(cards, '', true, false, new Set(), later(61));
assert.equal(cards[''].card.due, due);
recordPositionReview(cards, 'hint', true, true, new Set(), now);
assert.equal(cards.hint.recovered, false);
const restored = JSON.parse(JSON.stringify(stats));
recordPositionReview(positionReviews(restored, 0, 'a'), '', false, false, new Set(), later(86400));
assert.equal(restored.chapters.stable.positionReviews.cards[''].recovered, false);
const trees = [{ headers: {}, root: [
    { move: 'e4', children: [{ move: 'e5', children: [{ move: 'Nf3', children: [] }] },
        { move: 'c5', children: [{ move: 'Nf3', children: [] }] }] },
    { move: 'd4', children: [{ move: 'd5', children: [{ move: 'c4', children: [] }] }] }
] }, { headers: {}, root: [{ move: 'd4', children: [] }] }];
const catalog = positionCatalog(trees, 'white');
assert.deepEqual(Array.from(catalog, item => item.id), ['', 'e4|e5', 'e4|c5', 'd4|d5', '']);
assert.equal(catalog.find(item => item.id === 'e4|c5').path.join(','), '0,1');
const black = positionCatalog(trees, 'black');
assert.deepEqual(Array.from(black, item => item.id), ['e4', 'd4']);
const custom = positionCatalog([{ headers: { FEN: '7k/8/8/8/8/8/8/K7 b - - 0 1' }, root: [{ move: 'Kg8', children: [] }] }], 'white');
assert.equal(custom.length, 1);
const fresh = { chapters: {}, chapterIds: ['stable', 'second'] };
const session = { newCount: 0, lastChapter: null };
assert.equal(nextSmartPosition(fresh, signatures, catalog, session, now).target.type, 'line');
const freshCards = positionReviews(fresh, 0, 'a');
recordPositionReview(freshCards, '', false, false, new Set(), now);
const overdue = nextSmartPosition(fresh, signatures, catalog, session, later(700)).target;
assert.equal(overdue.type, 'position');
assert.equal(overdue.chapter, 0);
assert.equal(overdue.id, '');
session.newCount = 10;
const finished = nextSmartPosition(fresh, signatures, catalog, session, later(10));
assert.equal(finished.target, null);
assert(finished.nextDue > now.getTime());
const legacy = { chapters: { 0: { failedPositions: { signature: 'a', positions: { 'e4|c5': { cleanStreak: 0 } } } } } };
assert.equal(nextSmartPosition(legacy, signatures, catalog, { newCount: 10 }, now).target.id, 'e4|c5');
assert.equal(positionReviews(stats, 0, 'edited')[''], undefined);
assert.equal(stats.chapters.stable.positionReviews.signature, 'edited');
console.log('Position FSRS scheduling, corrections, hints, due priority, limits, identities and variations passed');

const { introducedMoves, recordIntroducedMove, recordContinuationReview, scheduledReviews, learningChain } = context;
const blend = { chapters: {}, chapterIds: ['one', 'two'] };
const blendCards = positionReviews(blend, 0, 'a');
recordPositionReview(blendCards, '', true, false, new Set(), now);
recordIntroducedMove(blendCards, '', 'e4');
blendCards[''].card.due = later(-60);
blendCards[''].card.last_review = later(-120);
blendCards[''].card.stability = 2;
const blendSession = { newCount: 0, reviewCount: 0, reviewStreak: 0 };
assert.equal(nextSmartPosition(blend, signatures, catalog, blendSession, now).target.type, 'line');
blendSession.newCount = 5;
assert.equal(nextSmartPosition(blend, signatures, catalog, blendSession, now).target.type, 'position');
blendSession.reviewCount = 5;
assert.equal(nextSmartPosition(blend, signatures, catalog, blendSession, now).target.type, 'line');
blendCards[''].recovered = false;
assert.equal(nextSmartPosition(blend, signatures, catalog, blendSession, now).target.type, 'position');
blendSession.reviewStreak = 3;
assert.equal(nextSmartPosition(blend, signatures, catalog, blendSession, now).target.type, 'line');
blendSession.newCount = 10;
assert.equal(nextSmartPosition(blend, signatures, catalog, blendSession, now).target.type, 'position');

const terminal = [{ headers: {}, root: [{ move: 'e4', children: [] }, { move: 'd4', children: [] }] }];
const terminalCatalog = positionCatalog(terminal, 'white');
const terminalStats = { chapters: {} };
const terminalCards = positionReviews(terminalStats, 0, 'a');
recordPositionReview(terminalCards, '', true, false, new Set(), now);
recordContinuationReview(terminalCards, '', 'e4', true, false, true, true, null, now);
recordIntroducedMove(terminalCards, '', 'e4');
const other = nextSmartPosition(terminalStats, ['a'], terminalCatalog, { newCount: 1 }, now).target;
assert.equal(other.type, 'line');
assert.equal(other.route.join(','), '1');
const matureCard = JSON.parse(JSON.stringify(terminalCards[''].card));
terminalCards[''].card.due = later(30 * 86400);
recordContinuationReview(terminalCards, '', 'd4', true, false, true, true, matureCard, now);
recordIntroducedMove(terminalCards, '', 'd4');
assert(new Date(terminalCards[''].moveReviews.d4.card.due) < later(86400));
assert.equal(new Date(terminalCards[''].card.due).getTime(), later(30 * 86400).getTime());
assert.equal(nextSmartPosition(terminalStats, ['a'], terminalCatalog, { newCount: 2 }, now).target, null);
const responseDue = new Date(terminalCards[''].moveReviews.d4.card.due);
terminalCards[''].moveReviews.e4.card.due = later(30 * 86400);
const responseTarget = nextSmartPosition(terminalStats, ['a'], terminalCatalog, { newCount: 10 }, responseDue).target;
assert.equal(responseTarget.expectedMove, 'd4');
const missedResponse = recordContinuationReview(terminalCards, '', 'd4', false, false, true, false, matureCard, responseDue);
assert.equal(missedResponse.recovered, false);
assert.equal(recordContinuationReview(terminalCards, '', 'd4', true, false, false, false, matureCard, responseDue), null);
assert.equal(terminalCards[''].moveReviews.d4.recovered, false);
const restoredTerminal = JSON.parse(JSON.stringify(terminalStats));
assert.equal(scheduledReviews(restoredTerminal, 'a', terminalCatalog[0]).length, 2);

const longMoves = ['e4', 'e5', 'Nf3', 'Nc6', 'Bb5', 'a6', 'Ba4', 'Nf6', 'O-O', 'Be7', 'Re1', 'b5', 'Bb3'];
const longRoot = longMoves.reduceRight((children, move) => [{ move, children }], []);
const longCatalog = positionCatalog([{ headers: {}, root: longRoot }], 'white');
const longStats = { chapters: {} };
const chain = learningChain(longStats, ['a'], longCatalog, longCatalog[0], 5);
assert.equal(chain.newMoves, 5);
assert.equal(chain.route.length, 9);
assert.equal(learningChain(longStats, ['a'], longCatalog, longCatalog[0], 1).route.length, 1);
const shortRoot = [{ move: 'e4', children: [{ move: 'e5', children: [] }] }];
const shortCatalog = positionCatalog([{ headers: {}, root: shortRoot }], 'white');
assert.equal(learningChain({ chapters: {} }, ['a'], shortCatalog, shortCatalog[0], 5).route.length, 1);
const migrated = { chapters: { stable: { attempts: 1, errors: 0, coveredMoves: ['e4'] } }, chapterIds: ['stable'] };
assert.deepEqual(Array.from(introducedMoves(migrated, 0, 'a', '')), ['e4']);
assert.equal(nextSmartPosition(migrated, ['a'], terminalCatalog, { newCount: 0 }, now).target.route.join(','), '1');
console.log('Balanced learning, urgent review bounds, response FSRS, terminal alternatives and bounded chains passed');
