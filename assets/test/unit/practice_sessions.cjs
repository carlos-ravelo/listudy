const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const context = vm.createContext({ ...require('ts-fsrs') });
for (const file of ['practice_sessions.js', 'progress_merge.js']) vm.runInContext(
    fs.readFileSync(path.join(__dirname, '../../js/modules/study', file), 'utf8')
        .replace(/^import .*\n/gm, '').replace(/export \{[^}]+\};/g, ''), context);
const { createPracticeTracker, sessionGoal, sessionDay, practiceTotals, mergeProgress } = context;
assert.equal(sessionGoal(null), 20);
assert.equal(sessionGoal('5'), 5);
assert.equal(sessionGoal('200'), 200);
for (const invalid of [0, 4, 201, 5.5, 'bad']) assert.equal(sessionGoal(invalid), 20);
const offlineId = createPracticeTracker({save() {}}).begin('positions').id;
assert.equal(typeof offlineId, 'string', 'Sessions work without the crypto API');
context.crypto = {};
const legacyId = createPracticeTracker({save() {}}).begin('positions').id;
assert.equal(typeof legacyId, 'string', 'Sessions work without randomUUID');
assert.notEqual(offlineId, legacyId);
context.crypto.randomUUID = () => 'native-session-id';
assert.equal(createPracticeTracker({save() {}}).begin('positions').id, 'native-session-id');
const sessions = {};
let nextId = 0;
const tracker = createPracticeTracker({ save: record => sessions[record.id] = record, id: () => `id-${++nextId}` });
tracker.begin('smart', 5, 0);
tracker.decision('one', true, true, true, 1000);
tracker.decision('two', false, false, false, 2000);
assert.equal(tracker.decision('two', false, true, false, 3000), false);
tracker.decision('three', false, true, true, 4000);
tracker.decision('four', false, true, false, 5000);
tracker.decision('five', false, true, false, 6000);
assert.equal(tracker.goalReached, true);
assert.equal(tracker.current.status, 'active', 'The goal does not interrupt the current chain');
tracker.decision('six', false, true, false, 7000);
tracker.end('goal', 8000);
assert.equal(sessions['id-1'].newCount, 1);
assert.equal(sessions['id-1'].reviewCount, 5);
assert.equal(sessions['id-1'].correctCount, 3);
assert.equal(sessions['id-1'].activeMs, 8000);
assert.equal(tracker.decision('seven', false, true, false, 9000), false);
tracker.begin('smart', 10, 10000);
assert.equal(tracker.current.goal, 10);
tracker.end('stopped', 11000);
assert.equal(Object.keys(sessions).length, 1, 'Empty sessions do not inflate history');

tracker.begin('lines', 20, 20000);
tracker.decision('a', false, true, false, 20000);
tracker.tick(30000);
tracker.tick(40000, false);
tracker.tick(100000, true);
tracker.activity(100000);
tracker.tick(110000);
assert.equal(tracker.current.activeMs, 30000, 'Hidden time is excluded');
tracker.tick(400000);
assert.equal(tracker.current.activeMs, 140000, 'Idle time stops after two minutes');
tracker.end('left', 400000);
const totals = practiceTotals(sessions, 400000);
assert.equal(totals.sessions, 2);
assert.equal(totals.decisions, 7);
assert.equal(totals.activeMs, 148000);
assert.equal(totals.todayDecisions, 7);

const midnight = new Date(2026, 9, 15, 23, 59, 30).getTime();
tracker.begin('smart', 20, midnight);
tracker.decision('m', true, true, true, midnight);
tracker.tick(midnight + 60000);
tracker.decision('n', false, true, false, midnight + 60000);
tracker.end('stopped', midnight + 60000);
assert.equal(tracker.current.days[sessionDay(midnight)].activeMs, 30000);
assert.equal(tracker.current.days[sessionDay(midnight + 60000)].activeMs, 30000);
assert.equal(tracker.current.days[sessionDay(midnight)].decisions, 1);
assert.equal(tracker.current.days[sessionDay(midnight + 60000)].decisions, 1);

const base = { version: 1, chapters: {}, studySessions: { one: { id: 'one', status: 'active', updatedAt: 10, newCount: 1, reviewCount: 0, activeMs: 1000 } } };
const local = structuredClone(base);
const remote = structuredClone(base);
local.studySessions.one = { ...local.studySessions.one, status: 'goal', updatedAt: 20, reviewCount: 4, activeMs: 6000 };
remote.studySessions.two = { id: 'two', status: 'left', updatedAt: 15, newCount: 2, reviewCount: 0, activeMs: 2000 };
const merged = mergeProgress(base, local, remote, 'study_chapter_stats');
assert.equal(merged.studySessions.one.activeMs, 6000);
assert.equal(merged.studySessions.one.reviewCount, 4);
assert.equal(Object.keys(merged.studySessions).length, 2);
assert.equal(practiceTotals(merged.studySessions).decisions, 7);
assert.equal(mergeProgress(merged, merged, merged).studySessions.one.activeMs, 6000);
const reset = { version: 1, chapters: {}, resetId: 'reset', resetAt: 30 };
assert.equal(Object.keys(mergeProgress(base, reset, remote).studySessions).length, 2,
    'Resetting memory progress preserves study effort');
console.log('Configurable goals, correction bounds, active time, day boundaries and session sync passed');
