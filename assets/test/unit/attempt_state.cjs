const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname, '../../js/modules/training/attempt_state.js'), 'utf8').replace(/^export /gm, ''), context);
const record = { attempts: 0, errors: 0, assisted: false, completed: false };
const attempt = context.createAttemptState(record);
assert.equal(attempt.active, true);
assert.equal(attempt.decision(true), true);
assert.equal(attempt.decision(false), true);
assert.equal(record.attempts, 2);
assert.equal(record.errors, 1);
assert.equal(record.assisted, false, 'The adapter decides whether an error counts as assistance');
assert.equal(attempt.assist(), true);
assert.equal(attempt.finish({ completed: true, endedAt: 0 }), true);
const completed = { ...record };
assert.equal(attempt.active, false);
assert.equal(attempt.decision(false), false);
assert.equal(attempt.assist(), false);
assert.equal(attempt.finish({ completed: false, revealed: true }), false);
assert.deepEqual(record, completed, 'A finished attempt ignores subsequent outcomes and decisions');
const retry = { attempts: 0, errors: 0, assisted: true };
const next = context.createAttemptState(retry);
assert.equal(next.active, true);
next.finish({ abandoned: true });
assert.equal(record.completed, true, 'A new attempt never changes the previous record');
assert.equal(retry.assisted, true, 'Rehearsed attempts retain their initial assistance');
console.log('Attempt state: decisions, assistance policy, terminal outcomes and independent retries passed');
