const assert = require('node:assert/strict');
const createLatestTask = require('./latest_task_helper.cjs');
const createPageScope = require('./page_scope_helper.cjs');
let cancelled = 0;
const tasks = createLatestTask({ onCancel: () => cancelled++ });
const first = tasks.start();
let currentDuringAbort;
first.signal.addEventListener('abort', () => { currentDuringAbort = first.isCurrent(); });
const second = tasks.start();
assert.equal(first.signal.aborted, true);
assert.equal(currentDuringAbort, false, 'Invalidate the task before abort callbacks run');
assert.equal(first.isCurrent(), false);
assert.equal(second.isCurrent(), true);
assert.equal(cancelled, 1);
first.finish();
assert.equal(second.isCurrent(), true, 'A stale finally must not release a newer task');
second.finish();
assert.equal(second.isCurrent(), false);
tasks.cancel();
assert.equal(second.signal.aborted, false, 'Finishing releases the task without aborting completed work');
assert.equal(cancelled, 1);
const third = tasks.start();
tasks.cancel(); tasks.cancel();
assert.equal(third.signal.aborted, true);
assert.equal(cancelled, 2, 'Cancel resources exactly once');
const other = createLatestTask(), independent = other.start();
const last = tasks.start();
tasks.destroy(); tasks.destroy();
assert.equal(last.isCurrent(), false);
assert.equal(last.signal.aborted, true);
assert.equal(tasks.start(), null, 'Destroyed owners cannot begin new work');
assert.equal(independent.isCurrent(), true, 'Independent task owners do not invalidate each other');
const scope = createPageScope();
const scoped = scope.use(createLatestTask());
const pending = scoped.start();
scope.destroy();
assert.equal(pending.signal.aborted, true);
assert.equal(pending.isCurrent(), false, 'Page/run teardown invalidates pending work');
other.destroy();
console.log('Latest tasks: supersession, abort ordering, stale finally, completion, independent owners and disposal passed');
