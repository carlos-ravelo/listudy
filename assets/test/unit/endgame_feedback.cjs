const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../../..');
const uri = source => 'data:text/javascript;base64,' + Buffer.from(source).toString('base64');
(async () => {
    const evaluation = uri(fs.readFileSync(path.join(root, 'assets/js/modules/sparring/evaluation.js'), 'utf8'));
    const source = fs.readFileSync(path.join(root, 'assets/js/modules/endgame_feedback.js'), 'utf8').replace("'./sparring/evaluation.js'", JSON.stringify(evaluation));
    const {endgameTurningPoint, endgameMateCue, createEndgameFeedback} = await import(uri(source));
    const barSource = fs.readFileSync(path.join(root, 'assets/js/modules/evaluation_bar.js'), 'utf8').replace("'./sparring/evaluation.js'", JSON.stringify(evaluation));
    const {evaluationBarValue, renderEvaluationBar} = await import(uri(barSource));
    assert.equal(evaluationBarValue(null), null);
    assert.deepEqual(evaluationBarValue({score: {type: 'cp', value: 0}, turn: 'b'}), {white: 50, text: '0.0'});
    assert.equal(evaluationBarValue({score: {type: 'cp', value: 250}, turn: 'b'}).text, '-2.5');
    assert.deepEqual(evaluationBarValue({score: {type: 'mate', value: -6}, turn: 'b'}), {white: 100, text: 'M6'});
    assert.deepEqual(evaluationBarValue({score: {type: 'mate', value: 0}, turn: 'w'}), {white: 0, text: '#'});
    const attrs = {}, styles = {}, label = {};
    const meter = {dataset: {}, style: {setProperty(key, value) {styles[key] = value;}}, querySelector: () => label, setAttribute(key, value) {attrs[key] = value;}, getAttribute(key) {return attrs[key];}};
    renderEvaluationBar(meter, {score: {type: 'cp', value: 500}, turn: 'w'}, 'white', {evaluation: 'Evaluation', analysing: 'Analysing'});
    const share = styles['--white-share'];
    renderEvaluationBar(meter, null, 'white', {analysing: 'Analysing'});
    assert.equal(styles['--white-share'], share, 'Pending searches do not reset the bar to equal');
    assert.equal(label.textContent, '+5.0');
    assert.equal(attrs['aria-busy'], 'true');
    const position = (cp, turn = 'w', depth = 18) => ({score: {type: 'cp', value: cp}, turn, depth});
    assert.equal(endgameTurningPoint(position(500), position(0, 'b'), 'w'), 'advantage');
    assert.equal(endgameTurningPoint(position(-500), position(0, 'b'), 'b'), 'advantage');
    assert.equal(endgameTurningPoint(position(500), position(0, 'b'), 'w', 'd'), null, 'Drawing goal should not penalise securing a draw');
    assert.equal(endgameTurningPoint(position(0), position(350, 'b'), 'w', 'd'), 'danger');
    assert.equal(endgameTurningPoint(position(500, 'w', 9), position(0, 'b'), 'w'), null);
    assert.equal(endgameTurningPoint(position(500), position(-400, 'b'), 'w'), null);
    assert.equal(endgameTurningPoint(position(500), {score: {type: 'mate', value: 0}, turn: 'b', depth: 99}, 'w'), null);
    for (const player of ['w', 'b']) {
        const opponent = player === 'w' ? 'b' : 'w';
        assert.deepEqual(endgameMateCue({score: {type: 'mate', value: -6}, turn: opponent}, player), {moves: 6, winning: true});
        assert.deepEqual(endgameMateCue({score: {type: 'mate', value: 6}, turn: opponent}, player), {moves: 6, winning: false});
    }
    assert.equal(endgameMateCue(position(600), 'w'), null);
    assert.equal(endgameMateCue({score: {type: 'mate', value: 0}, turn: 'b'}, 'w'), null);
    assert.equal(endgameMateCue(null, 'w'), null);
    const values = new Map();
    global.localStorage = {getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value)};
    const flush = () => new Promise(resolve => setImmediate(resolve));
    const row = (index = 0) => ({before: {initialFen: 'test', moves: Array(index * 2).fill('a1a2'), turn: 'w'}, after: {initialFen: 'test', moves: Array(index * 2 + 1).fill('a1a2'), turn: 'b'}, ply: index * 2 + 1, san: 'Ka2', uci: 'a1a2'});
    const toggle = {}, panel = {hidden: true}, notices = [], calls = [];
    let fail = false;
    const engine = {async analyze(state) {
        calls.push(state);
        if (fail) { fail = false; throw new Error('Unavailable'); }
        return {...position(state.moves.length % 2 ? 0 : 500, state.turn), uci: 'a1a2', pv: ['a1a2']};
    }};
    const feedback = createEndgameFeedback({engine, player: 'w', target: 'w', toggle, panel, labels: {advantage: 'Advantage reduced'}, onUpdate() {}, onNotice: text => notices.push(text)});
    feedback.record(row()); await flush();
    assert.equal(calls.length, 0, 'Default practice must not run grading searches');
    feedback.review(); await flush(); await flush();
    assert.equal(feedback.rows[0].assessment.grade, 'blunder');
    assert.equal(feedback.summary().done, 1);
    assert.equal(notices.length, 0, 'Review does not emit live notifications');
    feedback.close(); toggle.checked = true; toggle.onchange();
    assert.equal(values.get('endgame_live_feedback'), 'true');
    fail = true; feedback.record(row(1)); await flush(); await flush();
    assert.equal(feedback.rows[1].status, 'error');
    feedback.record({...row(2), goalReached: true}); await flush(); await flush();
    assert.equal(feedback.rows[2].status, 'done', 'One failed search must not break later analysis');
    assert.equal(feedback.rows[2].moment, null, 'Exercise goals override a raw evaluation drop');
    feedback.review(); await flush(); await flush();
    assert.equal(feedback.rows[1].status, 'done', 'Review can retry failed searches');
    const saved = feedback.snapshot(99);
    const completedCount = feedback.rows.filter(row => row.status === 'done').length;
    feedback.destroy();
    const searchesBeforeRestore = calls.length;
    const restored = createEndgameFeedback({engine, player: 'w', target: 'w', toggle: {}, panel: {}, labels: {}, saved, onUpdate() {}});
    restored.observe(row().before);
    assert(restored.currentAnalysis, 'Restored positions immediately reuse their existing evaluation');
    restored.review(); await flush(); await flush();
    assert.equal(restored.rows.filter(row => row.status === 'done').length, completedCount);
    assert.equal(calls.length, searchesBeforeRestore, 'Rollback does not reanalyse completed decisions');
    restored.destroy();
    values.set('endgame_live_feedback', 'false');
    const barToggle = {checked: false}, liveToggle = {};
    const barOnly = createEndgameFeedback({engine, player: 'w', target: 'w', toggle: liveToggle, evaluationToggle: barToggle, panel: {}, labels: {}, onUpdate() {}});
    barOnly.observe(row().before); await flush();
    assert.equal(barOnly.currentAnalysis, null);
    barToggle.checked = true; barToggle.onchange(); await flush(); await flush();
    assert(barOnly.currentAnalysis, 'Bar alone analyses the initial position');
    assert.equal(values.get('endgame_eval_bar'), 'true');
    assert.equal(barOnly.rows.length, 0, 'Bar does not grade unplayed moves');
    barOnly.destroy();
    values.set('endgame_live_feedback', 'true');
    let release, updated = 0;
    const stale = createEndgameFeedback({engine: {analyze: () => new Promise(resolve => { release = resolve; })}, player: 'w', target: 'w', toggle: {}, panel: {}, labels: {}, onUpdate: () => updated++, onNotice: () => assert.fail('Stale notification')});
    stale.record(row()); await flush();
    stale.destroy(); release({...position(500), uci: 'a1a2'}); await flush();
    assert.equal(updated, 0, 'Disposed sessions must not update a new exercise');
    console.log('Endgame outcome estimates, confidence, default-off analysis, retry after failure, goals and stale sessions passed');
})().catch(error => {console.error(error); process.exitCode = 1;});
