const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname, '../../js/modules/study/run_lifecycle.js'), 'utf8')
    .replace(/^export /gm, ''), context);
(async () => {
    let chapter = 0, finishes = 0, advances = 0;
    const pending = [];
    const run = context.createStudyRun({ getChapter: () => chapter, pause: () => {},
        replay: options => new Promise((resolve, reject) => pending.push({ options, resolve, reject })) });
    const options = { root: [], path: [], count: 0, present() {}, advance: () => advances++, finish: () => finishes++ };
    assert.equal(run.revision, 0);
    assert.equal(run.replaying, false);
    const first = run.replayPosition(options);
    assert.equal(run.replaying, true);
    assert.equal(pending[0].options.isCurrent(), true);
    const second = run.replayPosition(options);
    assert.equal(pending[0].options.isCurrent(), false);
    pending[0].resolve(false); await first;
    assert.equal(run.replaying, true, 'An older replay cannot clear its replacement');
    assert.equal(finishes, 0);
    pending[1].resolve(true); assert.equal(await second, true);
    assert.equal(run.replaying, false);
    assert.equal(finishes, 1);
    const changedChapter = run.replayPosition(options);
    chapter = 1;
    assert.equal(pending[2].options.isCurrent(), false, 'A chapter change invalidates replay even without an explicit reset');
    run.invalidate(); run.stopReplay();
    pending[2].resolve(false); await changedChapter;
    assert.equal(finishes, 1);
    const failure = run.replayPosition(options);
    pending[3].reject(new Error('Replay failed'));
    await assert.rejects(failure, /Replay failed/);
    assert.equal(run.replaying, false, 'A current replay releases its lock after failure');
    assert.equal(finishes, 2);
    const destroyed = run.replayPosition(options);
    const revision = run.revision;
    run.destroy();
    assert.equal(run.isCurrent(revision), false);
    assert.equal(pending[4].options.isCurrent(), false);
    pending[4].resolve(false); await destroyed;
    assert.equal(finishes, 2);
    assert.equal(run.replaying, false);
    assert.equal(await run.replayPosition(options), false);
    assert.equal(pending.length, 5);
    assert.equal(advances, 0);
    console.log('Study run lifecycle: revisions, overlapping replays, chapter changes, errors and teardown passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
